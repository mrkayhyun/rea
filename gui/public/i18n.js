export const SUPPORTED = ["en", "ko"];

export function detectLang(stored, navigatorLanguages) {
  if (SUPPORTED.includes(stored)) return stored;
  const languages = Array.isArray(navigatorLanguages) ? navigatorLanguages : [];
  for (const language of languages) {
    if ("string" == typeof language && language.toLowerCase().startsWith("ko"))
      return "ko";
  }
  return "en";
}

export function translate(lang, key, vars) {
  const table = MESSAGES[lang] || MESSAGES.en;
  let value =
    table && Object.prototype.hasOwnProperty.call(table, key)
      ? table[key]
      : undefined;
  if (void 0 === value && "en" !== lang && MESSAGES.en)
    value = Object.prototype.hasOwnProperty.call(MESSAGES.en, key)
      ? MESSAGES.en[key]
      : undefined;
  if (void 0 === value) value = key;
  if (vars)
    for (const name of Object.keys(vars))
      value = value.split("{" + name + "}").join(String(vars[name]));
  return value;
}
